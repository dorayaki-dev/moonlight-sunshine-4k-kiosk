#!/usr/bin/env bash
# hdmi-audio.sh — find the TV's HDMI audio device, point ALSA at it, and un-mute it.
#
# 用法 / Usage:  HDMI_DEV=$(sudo bash hdmi-audio.sh) ; export AUDIODEV="$HDMI_DEV"
#
# 它做三件事 / It does three things:
#   1. 探测 HDMI 声卡（card/device 序号重启后会漂移，所以每次启动都重新探测）
#   2. 写 /etc/asound.conf，把 pcm.!default / ctl.!default 指过去（SDL 不认 AUDIODEV 时的兜底）
#   3. 打开 IEC958 输出开关 —— 这是"数据在流但电视没声"的元凶
set -uo pipefail

LINE=$(aplay -l 2>/dev/null | grep -m1 -i "HDMI" || true)
if [ -z "$LINE" ]; then
  echo "hdmi-audio: no HDMI PCM found (is the TV connected and the output active?)" >&2
  exit 1
fi

CARD=$(echo "$LINE" | grep -oE "^card [0-9]+"  | grep -oE "[0-9]+")
DEV=$(echo  "$LINE" | grep -oE "device [0-9]+" | grep -oE "[0-9]+")

echo "hdmi-audio: $LINE" >&2

# 2) ALSA default → HDMI
cat > /etc/asound.conf <<EOF
# generated by hdmi-audio.sh — points the default PCM at the TV's HDMI output
pcm.!default { type hw; card ${CARD}; device ${DEV} }
ctl.!default { type hw; card ${CARD}; device ${DEV} }
EOF

# 3) un-mute the HDMI output (IEC958). 实测这行不加上就会出现"日志全正常、电视无声"
amixer -c "${CARD}" sset "IEC958" on     >/dev/null 2>&1 || true
amixer -c "${CARD}" sset "IEC958" unmute >/dev/null 2>&1 || true
alsactl store >/dev/null 2>&1 || true

# 1) hand the device string back to the caller
echo "hw:${CARD},${DEV}"
